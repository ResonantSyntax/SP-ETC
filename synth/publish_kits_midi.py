"""Generate the guarded browser overlay for the experimental v9.44-test1 MIDI kit build only.

    python synth/publish_kits_midi.py /path/to/stock/SP404MKII_APP1.bin --candidate out/kits-v944/SP404MKII_APP1.bin

Writes kits-midi-data.js (window.DOOMOS_KITS_MIDI / DOOMOS_KITS_MIDI_PATCH), which
the patcher on main offers as a separate test option beside the published v9.43.
"""
import argparse,base64,json
from pathlib import Path
import build
from kits.build_arp_kit import expand_kit_sources
EXPECTED_SHA='d47f46d4204a90366ac06774050b9ee4c7b9cdfb6470ca65be9f10c24ad1a51d'
EXPECTED_SIZE=3088608
REVISION='v9.44-test1'
LABEL='5.52+kits-v9.44t'
HERE=Path(__file__).resolve().parent

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('stock',type=Path);p.add_argument('--candidate',type=Path,required=True);a=p.parse_args()
    stock=a.stock.read_bytes();build.require_hash(stock,build.v2.STOCK_SHA256,'stock APP1')
    build.require_hash(a.stock.with_name('SP404MKII_APP0.bin').read_bytes(),build.APP0_SHA,'stock APP0')
    image=a.candidate.read_bytes();m=json.loads(a.candidate.with_name('manifest.json').read_text())
    build.require_hash(image,EXPECTED_SHA,'MIDI test kits APP1')
    if len(image)!=EXPECTED_SIZE or m['sha256']!=EXPECTED_SHA or m['revision']!=REVISION or not m['synthesis_only'] or m['kit_selector_range']!=[1,13]:raise ValueError('unexpected MIDI test candidate metadata')
    _,current=expand_kit_sources(HERE/'kits/kit_engine.c')
    if current!=m['kit_source_sha256']:raise ValueError('runtime source inventory differs')
    for name,h in m['kit_source_sha256'].items():
        path=(HERE/'kits'/name).resolve()
        if not path.is_relative_to((HERE/'kits').resolve()):raise ValueError('source path escapes kits')
        build.require_hash(path.read_text().encode(),h,name)
    base,_=build.build(stock);overlay=build.make_overlay(base,image,LABEL)
    metadata=dict(revision=REVISION,sha256=EXPECTED_SHA,size=EXPECTED_SIZE,base_sha256=build.sha(base),kits=m['arp_menu']['KIT'][1:],kit_selector_range=[1,13],synthesis_only=True,hardware_verified=False,experimental=True,source_branch='claude/kits-midi')
    text='// Generated by synth/publish_kits_midi.py on branch claude/kits-midi. Guarded overlay; no complete firmware.\n'
    text+='window.DOOMOS_KITS_MIDI = '+json.dumps(metadata,sort_keys=True)+';\n'
    text+='window.DOOMOS_KITS_MIDI_PATCH = '+json.dumps(base64.b64encode(overlay).decode('ascii'))+';\n'
    (build.REPO/'kits-midi-data.js').write_text(text,encoding='ascii',newline='\n')
    print('Verified v9.44-test1 MIDI kit overlay:',build.sha(image))
if __name__=='__main__':main()
