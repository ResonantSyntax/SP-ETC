"""Generate a guarded browser overlay for the tested v9.46 kit release only.

v9.46 is build v9.46-test3 (the kit stage) plus the RESAMPLE start fix
(build_start_fix.py, a stage after it). The overlay turns the DOOM OS base into
the final image; both stages are checked against their exact hashes.

usage: python synth/publish_kits.py /path/to/stock/SP404MKII_APP1.bin \
           --kit-stage out/kits-v946 --candidate out/kits-v946-final/SP404MKII_APP1.bin
"""
import argparse,base64,json
from pathlib import Path
import build
from kits.build_arp_kit import expand_kit_sources
EXPECTED_SHA='7b5fbcb4c3ce1e8782fef4b5803be74c7d14eddf25a1b53682abe00c9ed3684a'
EXPECTED_SIZE=3094624
KIT_STAGE_SHA='88384c3c9760559e721c1a14973ef3a2ced6abf016572b0a73c5dfb0cef492ba'
KIT_REVISION='v9.46-test3'
START_FIX='resample-startfix-2'
HERE=Path(__file__).resolve().parent

def main():
    p=argparse.ArgumentParser(description=__doc__,formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('stock',type=Path)
    p.add_argument('--kit-stage',type=Path,required=True,help='folder with the kit stage SP404MKII_APP1.bin and manifest.json')
    p.add_argument('--candidate',type=Path,required=True,help='the final SP404MKII_APP1.bin (start-fix stage), manifest.json beside it')
    a=p.parse_args()
    stock=a.stock.read_bytes();build.require_hash(stock,build.v2.STOCK_SHA256,'stock APP1')
    build.require_hash(a.stock.with_name('SP404MKII_APP0.bin').read_bytes(),build.APP0_SHA,'stock APP0')
    kit_image=(a.kit_stage/'SP404MKII_APP1.bin').read_bytes();m=json.loads((a.kit_stage/'manifest.json').read_text())
    build.require_hash(kit_image,KIT_STAGE_SHA,'kit stage APP1')
    if m['sha256']!=KIT_STAGE_SHA or m['revision']!=KIT_REVISION or not m['synthesis_only'] or m['kit_selector_range']!=[1,13]:
        raise ValueError('unexpected kit stage metadata')
    image=a.candidate.read_bytes();final=json.loads(a.candidate.with_name('manifest.json').read_text())
    build.require_hash(image,EXPECTED_SHA,'tested kits APP1')
    if (len(image)!=EXPECTED_SIZE or final['sha256']!=EXPECTED_SHA or final['revision']!=START_FIX or
            final['parent_sha256']!=KIT_STAGE_SHA or final['parent_revision']!=KIT_REVISION):
        raise ValueError('unexpected start-fix stage metadata')
    _,current=expand_kit_sources(HERE/'kits/kit_engine.c')
    if current!=m['kit_source_sha256']:raise ValueError('runtime source inventory differs')
    for name,h in m['kit_source_sha256'].items():
        path=(HERE/'kits'/name).resolve()
        if not path.is_relative_to((HERE/'kits').resolve()):raise ValueError('source path escapes kits')
        build.require_hash(path.read_text().encode(),h,name)
    base,_=build.build(stock);overlay=build.make_overlay(base,image,'5.52+kits-v9.46')
    metadata=dict(release='v9.46',revision=KIT_REVISION,start_fix=START_FIX,sha256=EXPECTED_SHA,size=EXPECTED_SIZE,
                  kit_stage_sha256=KIT_STAGE_SHA,base_sha256=build.sha(base),kits=m['arp_menu']['KIT'][1:],
                  kit_selector_range=[1,13],synthesis_only=True,hardware_verified=False)
    text='// Generated by synth/publish_kits.py. Guarded overlay; no complete firmware.\n'
    text+='window.DOOMOS_KITS = '+json.dumps(metadata,sort_keys=True)+';\n'
    text+='window.DOOMOS_KITS_PATCH = '+json.dumps(base64.b64encode(overlay).decode('ascii'))+';\n'
    (build.REPO/'kits-data.js').write_text(text,encoding='ascii',newline='\n')
    print('Verified v9.46 kit overlay:',build.sha(image))
if __name__=='__main__':main()
