"""Generate a guarded browser overlay for the tested v9.43 candidate only."""
import argparse,base64,json
from pathlib import Path
import build
from kits.build_arp_kit import expand_kit_sources
EXPECTED_SHA='f6b83372d10d96b8fb070df6790f6e5ed375a457391cab43eae2e9233848a515'
EXPECTED_SIZE=3085968
HERE=Path(__file__).resolve().parent

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('stock',type=Path);p.add_argument('--candidate',type=Path,required=True);a=p.parse_args()
    stock=a.stock.read_bytes();build.require_hash(stock,build.v2.STOCK_SHA256,'stock APP1')
    build.require_hash(a.stock.with_name('SP404MKII_APP0.bin').read_bytes(),build.APP0_SHA,'stock APP0')
    image=a.candidate.read_bytes();m=json.loads(a.candidate.with_name('manifest.json').read_text())
    build.require_hash(image,EXPECTED_SHA,'tested kits APP1')
    if len(image)!=EXPECTED_SIZE or m['sha256']!=EXPECTED_SHA or m['revision']!='v9.43-test3' or not m['synthesis_only'] or m['kit_selector_range']!=[1,13]:raise ValueError('unexpected kit candidate metadata')
    _,current=expand_kit_sources(HERE/'kits/kit_engine.c')
    if current!=m['kit_source_sha256']:raise ValueError('runtime source inventory differs')
    for name,h in m['kit_source_sha256'].items():
        path=(HERE/'kits'/name).resolve()
        if not path.is_relative_to((HERE/'kits').resolve()):raise ValueError('source path escapes kits')
        build.require_hash(path.read_text().encode(),h,name)
    base,_=build.build(stock);overlay=build.make_overlay(base,image,'5.52+kits-v9.43')
    metadata=dict(revision=m['revision'],sha256=EXPECTED_SHA,size=EXPECTED_SIZE,base_sha256=build.sha(base),kits=m['arp_menu']['KIT'][1:],kit_selector_range=[1,13],synthesis_only=True,hardware_verified=False)
    text='// Generated by synth/publish_kits.py. Guarded overlay; no complete firmware.\n'
    text+='window.DOOMOS_KITS = '+json.dumps(metadata,sort_keys=True)+';\n'
    text+='window.DOOMOS_KITS_PATCH = '+json.dumps(base64.b64encode(overlay).decode('ascii'))+';\n'
    (build.REPO/'kits-data.js').write_text(text,encoding='ascii',newline='\n')
    print('Verified v9.43 kit overlay:',build.sha(image))
if __name__=='__main__':main()
